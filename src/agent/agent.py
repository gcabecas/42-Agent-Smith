class SolutionOutput(BaseModel):
    """Output from student solution, required format for evaluation.
    This is the JSON structure your agent must produce and write to solution.
    json.
    The moulinette validates this against task correctness and metrics limits.
    """
    task_id: str = Field(description="Task identifier (MBPP task_id a string, or SWE-bench instance_id)")
    benchmark: str = Field(description="Benchmark type: 'mbpp' or  swebench'")

    success: bool = Field(default=False, description="Whether the agent believes i solved the task")
    solution: str = Field(default="", description="For MBPP: the Python function code For SWE-bench: the git patch (diff)")
    iterations: int = Field(default=0, description="Number of agent loop iteration used")
    total_requests: int = Field(default=0, description="Total number of LLM AP requests made (including retries)")

    total_input_tokens: int = Field(default=0, description="Sum of input_token across all steps")
    total_output_tokens: int = Field(default=0, description="Sum of output_token across all steps")

    total_time_seconds: float = Field(default=0, description="Wall-clock time fro agent start to finish")
    steps: list[StepMetrics] = Field(default_factory=list, description="Per step metrics, one entry per agent iteration")
    system_prompt: str = Field(description="Full system prompt sen to the LLM (for provenance checking)")
    error: Optional[str] = Field(default=None, description="Error message i the agent failed (None if successful)")
    timestamp: str = Field(default_factory=lambda: datetime.now().isoformat(), description="ISO 8601 timestamp of when the solution was produced")


class Agent(SolutionOutput):
    model_config = {"arbitrary_types_allowed": True}

    output_path: str = Field(pattern=r".*\.json$")

    llmapi: LlmApi
    prompt: MemoryPrompt
    exec_result: str = ""
   
    def create_prompt(self) -> str:
        if self.exec_result:
            out = BasePrompts.get_aftercode_prompt(self.exec_result)
        else:
            out = BasePrompts.get_nocode_prompt()
        return out

    def next_step(self) -> bool:
   
        start = datetime.now()
        prompt = self.create_prompt()

        new = StepMetrics(step=len(self.steps) + 1)
        self.steps.append(new)
        self.prompt.add_message(prompt)
        resp = self.llmapi.response(self.prompt.messages)
        code = self.prompt.get_message_code(self.llmapi.get_current())

        self.exec_result = ""
        if code:
            command = ["uv", "run", "sandbox;", code]  # TODO use arguments in a json file
            result = subprocess.run(
                command,
                cwd=".",
                capture_output=True,
                text=True,
                check=True,
            )
            read = str(result.stdout)
            self.exec_result = read
            new.sandbox_input = code
            new.sandbox_output = read

        new.llm_output = resp["llm_output"]
        new.input_tokens = resp["input_tokens"]
        new.output_tokens = resp["output_tokens"]
        new.model_name = resp["model_name"]
        new.retries = resp["retries"]
        self.total_input_tokens += resp["input_tokens"]
        self.total_output_tokens += resp["output_tokens"]
        new.request_time_ms = datetime.now() - start

        print("[ STEP FINISHED ]------------------", file=sys.stderr) 
        for key, elem in new.__dict__.items():
            print(f"{key}|=|{elem}", file=sys.stderr)
        return False


